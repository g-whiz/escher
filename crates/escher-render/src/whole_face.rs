const VERTEX_MIRROR: usize = 1;

/// The faces of a tiling by polygons, with the stabilizer of one face of each
/// face type and its edges, on which an arrangement puts its pictures.
///
/// Build it with [`WholeFace::new`] from a Wythoff construction: a regular
/// tiling `{p,q}` with `p >= q >= 3`, or a construction with two or three
/// face types. The regular tilings are the marks with only mark 1 on, whose
/// faces have `p` sides and are centred at corner 0 of the triangle, and the
/// marks with only mark 0 on, whose faces have `q` sides and are centred at
/// corner 1. Each face type has a reference face, the face centred at its
/// corner of the domain, and the elements of the group that map it onto
/// itself form its stabilizer, of order `2 n` for a corner of order `n`: the
/// rotations and reflections generated by the reflections in the two sides
/// of the domain through that corner. A face of a corner with both of its
/// mirrors on has `2 n` sides, and any other face `n` sides.
///
/// An arrangement is a colouring of the side presentation in whose coset
/// table no element of the stabilizer of any face type other than the
/// identity fixes a coset. Its subgroup then maps no face onto itself other
/// than by the identity. Its number of colours is a multiple of the
/// [`index`](WholeFace::index), and it has that number divided by `2 n`
/// orbits on the faces of a type of corner order `n`. Each orbit is a
/// picture: the faces of one orbit show one painted picture, turned or
/// mirrored. On a regular tiling the pictures are named A, B, C, and so on.
/// With several face types, a picture is named by the position of the corner
/// of its type and its letter within the type, such as `0A` or `1B`. The
/// pictures are numbered from 0 over all types, by type in the order of the
/// corners and then by letter. Find the arrangements with
/// [`free_classes_of_index`](escher_group::free_classes_of_index) from the
/// [`presentation`](WholeFace::presentation), the
/// [`stabilizer`](WholeFace::stabilizer), and a multiple of the
/// [`index`](WholeFace::index), and read which edge of which picture meets
/// which with [`edges`](WholeFace::edges).
///
/// The pictures are read from the coset table: a breadth-first traversal from
/// coset 0, which reads at each coset the generators in order, each before its
/// inverse, reaches each coset first by one word. For each face type, its
/// picture A holds coset 0, and each further picture of the type starts at
/// the first coset of the traversal that the earlier pictures of the type do
/// not hold. The face of that coset is the reference face of the picture,
/// and the word that carries the reference face of the type onto it is the
/// word of the traversal, with the side through the centre of the face that
/// gives edge 0 its midpoint appended when the word has an odd number of
/// letters, so that the word preserves orientation.
///
/// Each picture lies on a flat regular polygon, its face mask, with the edges
/// numbered counterclockwise. The polygon is turned so that a picture painted
/// on it appears the same way up at the centre of the reference face of that
/// picture in the default view of the geometry, which is the Poincare disk,
/// the plane, or the ball with no rotation, whatever the render options say.
/// So the face masks do not change with the view options.
/// [`render_mask`](WholeFace::render_mask) draws them, and a [`WholeFaceFill`]
/// puts the pictures painted over them on the faces.
///
/// That the stabilizer of each face type is the group of the two reflections,
/// that the subgroups that meet the condition above map no face onto itself,
/// that the pictures are the orbits of the arrangement on the faces, and that
/// the edge pairing is read correctly from the coset table, are results that
/// no source that the crate rests on states, and the tests of the crate check
/// them on the tilings that they render.
///
/// # Examples
///
/// ```
/// use escher_domain::FundamentalDomain;
/// use escher_group::{SearchBudget, free_classes_of_index};
/// use escher_render::{WholeFace, Wythoff};
/// use escher_signature::Signature;
///
/// let domain = FundamentalDomain::build(&"*632".parse::<Signature>()?)?;
/// let hexagons = WholeFace::new(&domain, Wythoff::new(&domain, [false, true, false])?)?;
/// assert_eq!(hexagons.index(), 12);
/// assert_eq!(hexagons.stabilizer().len(), 11);
/// let found = free_classes_of_index(
///     hexagons.presentation(),
///     hexagons.stabilizer(),
///     2 * hexagons.index(),
///     SearchBudget::DEFAULT,
/// )?;
/// let first = found.list().first().ok_or("no arrangement")?;
/// let edges = hexagons.edges(first)?;
/// assert_eq!(edges.len(), 12);
/// assert!(edges.iter().all(|meeting| meeting.picture() < 2 && meeting.partner() < 6));
///
/// let octagons = WholeFace::new(&domain, Wythoff::new(&domain, [true, true, true])?)?;
/// let sides: Vec<u32> = octagons.face_types().iter().map(|kind| kind.sides()).collect();
/// assert_eq!(sides, [12, 6, 4]);
/// assert_eq!(octagons.index(), 12);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
#[derive(Clone, Debug, PartialEq)]
pub struct WholeFace {
    wythoff: Box<Wythoff>,
    presentation: Presentation,
    kinds: Vec<Kind>,
    corner_kinds: [Option<usize>; 3],
    types: Vec<FaceType>,
    stabilizer: Vec<Word>,
    index: u32,
    least: usize,
    edge_words: Vec<Word>,
    geometry: Geometry,
    pairings: Vec<DMat3>,
}

/// One face type of a [`WholeFace`], which [`WholeFace::face_types`]
/// returns: the corner of the triangle at which its faces are centred, the
/// order of that corner, and the number of sides of its faces.
///
/// # Examples
///
/// ```
/// use escher_domain::FundamentalDomain;
/// use escher_render::{WholeFace, Wythoff};
/// use escher_signature::Signature;
///
/// let domain = FundamentalDomain::build(&"*442".parse::<Signature>()?)?;
/// let tiles = WholeFace::new(&domain, Wythoff::new(&domain, [true, true, true])?)?;
/// let kinds: Vec<(u32, u32, u32)> = tiles
///     .face_types()
///     .iter()
///     .map(|kind| (kind.corner(), kind.order(), kind.sides()))
///     .collect();
/// assert_eq!(kinds, [(0, 4, 8), (1, 4, 8), (2, 2, 4)]);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct FaceType {
    corner: u32,
    order: u32,
    sides: u32,
}

impl FaceType {
    /// Returns the position of the corner of the triangle at which the faces
    /// of this type are centred, which is below 3.
    #[must_use]
    pub fn corner(self) -> u32 {
        self.corner
    }

    /// Returns the order of the corner, from 2 to 100.
    #[must_use]
    pub fn order(self) -> u32 {
        self.order
    }

    /// Returns the number of sides of a face of this type: the order of the
    /// corner when one mirror through it is on, and twice the order when both
    /// are.
    #[must_use]
    pub fn sides(self) -> u32 {
        self.sides
    }
}

/// How the face across one edge of the reference face of a picture of a
/// [`WholeFace`] meets it, which [`WholeFace::edges`] returns.
///
/// The neighbour across edge `i` of a picture shows the picture
/// [`picture`](EdgeMeeting::picture), as its face mask shows it, moved so
/// that its edge [`partner`](EdgeMeeting::partner) lies on edge `i`. It is
/// turned when the move preserves orientation, and mirrored when it reverses
/// it, both measured against the face masks of the two pictures. An edge may
/// meet itself: a turned neighbour is then the picture turned half a turn
/// about the midpoint of the edge, and a mirrored one is the picture
/// reflected in the edge.
///
/// # Examples
///
/// ```
/// use escher_domain::FundamentalDomain;
/// use escher_group::{SearchBudget, free_classes_of_index};
/// use escher_render::{WholeFace, Wythoff};
/// use escher_signature::Signature;
///
/// let domain = FundamentalDomain::build(&"*442".parse::<Signature>()?)?;
/// let squares = WholeFace::new(&domain, Wythoff::new(&domain, [false, true, false])?)?;
/// let found = free_classes_of_index(
///     squares.presentation(),
///     squares.stabilizer(),
///     2 * squares.index(),
///     SearchBudget::DEFAULT,
/// )?;
/// for arrangement in found.list() {
///     let edges = squares.edges(arrangement)?;
///     for (edge, meeting) in (0..).zip(&edges) {
///         let back = 4 * meeting.picture() + meeting.partner();
///         let back = edges.get(usize::try_from(back)?).ok_or("no partner")?;
///         assert_eq!(4 * back.picture() + back.partner(), edge);
///         assert_eq!(back.mirrored(), meeting.mirrored());
///     }
/// }
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct EdgeMeeting {
    picture: u32,
    partner: u32,
    mirrored: bool,
}

impl EdgeMeeting {
    /// Returns the picture of the neighbour, from 0, which is below the
    /// number of pictures of the arrangement.
    #[must_use]
    pub fn picture(self) -> u32 {
        self.picture
    }

    /// Returns the edge of the neighbour that lies on this edge, which is
    /// below the number of edges of the face of the neighbour.
    #[must_use]
    pub fn partner(self) -> u32 {
        self.partner
    }

    /// Returns whether the neighbour is a mirror image of the picture on its
    /// face mask, and not a turned copy.
    #[must_use]
    pub fn mirrored(self) -> bool {
        self.mirrored
    }
}

