    fn closed_orbits(table: &CosetTable, rule: TypeRule) -> Vec<usize> {
        let columns = [rule.centre, rule.vertex]
            .map(|side| Word::from_iter([crate::golden_images::letter(side)]));
        let mut orbit: Vec<Option<usize>> = vec![None; table.index()];
        let mut count = 0;
        for start in 0..table.index() {
            if orbit[start].is_some() {
                continue;
            }
            orbit[start] = Some(count);
            let mut stack = vec![start];
            while let Some(from) = stack.pop() {
                for column in &columns {
                    let to = trace_from(table, from, column);
                    if orbit[to].is_none() {
                        orbit[to] = Some(count);
                        stack.push(to);
                    }
                }
            }
            count += 1;
        }
        orbit
            .into_iter()
            .map(|orbit| orbit.unwrap_or_else(|| panic!("a coset has no orbit")))
            .collect()
    }

