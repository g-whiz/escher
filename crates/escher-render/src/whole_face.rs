    pub(super) fn on_surface_f64(
        measure: Measure,
        centre: &Vector,
        point: &Vector,
        weight: f64,
    ) -> Vector {
        let moved = [0, 1, 2].map(|index| {
            escher_reference::add(
                &escher_reference::mul(&num(1.0 - weight), &point[index]),
                &escher_reference::mul(&num(weight), &centre[index]),
            )
        });
        oriented(measure, centre, &moved)
    }

