#[expect(
    clippy::expect_used,
    reason = "a side of a triangle is numbered below 3, which fits a byte"
)]
fn letter(side: usize) -> Letter {
    Letter::generator(u8::try_from(side).expect("internal error: a side number fits a byte"))
}

#[expect(
    clippy::expect_used,
    reason = "a picture and an edge are numbered below the number of cosets of a table or the number of sides of a face, which fit u32"
)]
fn to_u32(value: usize) -> u32 {
    u32::try_from(value).expect("internal error: a picture or an edge number fits u32")
}

const fn other_side(corner: usize, side: usize) -> usize {
    if side == corner {
        (corner + 1) % 3
    } else {
        corner
    }
}

fn reflection(start: DVec2, end: DVec2) -> DMat2 {
    let direction = (end - start).normalize();
    DMat2::from_cols(
        DVec2::new(
            2.0 * direction.x * direction.x - 1.0,
            2.0 * direction.x * direction.y,
        ),
        DVec2::new(
            2.0 * direction.x * direction.y,
            2.0 * direction.y * direction.y - 1.0,
        ),
    )
}

fn face_angle(geometry: Geometry, centre: DVec3, foot: DVec3) -> f64 {
    let toward = match geometry {
        Geometry::Euclidean => (foot - centre).truncate(),
        Geometry::Hyperbolic => {
            hyperbolic::to_disk(hyperbolic::inverse(hyperbolic::translation(centre)) * foot)
        }
        Geometry::Spherical => (foot - centre * centre.dot(foot)).truncate(),
    };
    if toward == DVec2::ZERO {
        -PI / 2.0
    } else {
        toward.y.atan2(toward.x)
    }
}

fn flat_face(sides: u32, turn: f64, radius: f64) -> Vec<DVec2> {
    let count = f64::from(sides);
    (0..sides)
        .map(|vertex| {
            let angle = turn + f64::from(2 * vertex + 1) * PI / count;
            let (sin, cos) = angle.sin_cos();
            DVec2::new(cos, sin) * radius
        })
        .collect()
}

fn midpoint(polygon: &[DVec2], edge: usize) -> DVec2 {
    let count = polygon.len();
    (polygon[(edge + count - 1) % count] + polygon[edge]) / 2.0
}

fn nearest_edge(polygon: &[DVec2], point: DVec2) -> usize {
    (0..polygon.len())
        .min_by(|&first, &second| {
            let distance = |edge| midpoint(polygon, edge).distance_squared(point);
            distance(first).total_cmp(&distance(second))
        })
        .unwrap_or(0)
}

const fn greatest_common_divisor(first: usize, second: usize) -> usize {
    if second == 0 {
        first
    } else {
        greatest_common_divisor(second, first % second)
    }
}

fn stabilizer_elements(
    [centre_letter, vertex_letter]: [Letter; 2],
    [centre_matrix, vertex_matrix]: [DMat2; 2],
    order: u32,
) -> (Vec<Word>, Vec<DMat2>) {
    let rotation = centre_matrix * vertex_matrix;
    let mut words = Vec::new();
    let mut matrices = Vec::new();
    let mut turned = DMat2::IDENTITY;
    for turns in 0..order {
        let letters: Vec<Letter> = (0..turns)
            .flat_map(|_| [centre_letter, vertex_letter])
            .collect();
        words.push(letters.iter().copied().collect::<Word>());
        matrices.push(turned);
        words.push(letters.iter().copied().chain([centre_letter]).collect());
        matrices.push(turned * centre_matrix);
        turned *= rotation;
    }
    (words, matrices)
}

#[expect(
    clippy::expect_used,
    reason = "the rotations of the stabilizer carry the midpoint of edge 0 to every other edge of a face whose sides alternate between two kinds, and the reflections the midpoint of edge 1 to the rest, so every edge is reached"
)]
fn edge_starts(polygon: &[DVec2], matrices: &[DMat2], domain_edges: usize) -> Vec<(usize, usize)> {
    (0..polygon.len())
        .map(|edge| {
            matrices
                .iter()
                .enumerate()
                .find_map(|(word, &matrix)| {
                    (0..domain_edges)
                        .find(|&start| {
                            nearest_edge(polygon, matrix * midpoint(polygon, start)) == edge
                        })
                        .map(|start| (word, start))
                })
                .expect("internal error: the stabilizer carries an edge of the domain onto every edge of the face")
        })
        .collect()
}

#[expect(
    clippy::expect_used,
    reason = "every word traced here is in the generators of the table, or in the sides of the domain once the reading has checked that the table has one generator for each side, and starts at a coset below the index, and a complete table takes such a word to a coset below the index"
)]
fn traced(table: &CosetTable, coset: usize, word: &Word) -> usize {
    u32::try_from(coset)
        .ok()
        .and_then(|coset| table.trace(coset, word))
        .and_then(|coset| usize::try_from(coset).ok())
        .expect("internal error: a word in the generators of a complete coset table takes each coset to a coset")
}

fn reach_words(table: &CosetTable) -> Vec<(usize, Word)> {
    let mut reached = vec![false; table.index()];
    let mut order = Vec::with_capacity(table.index());
    reached[0] = true;
    let mut queue = VecDeque::from([(0, Word::new())]);
    while let Some((coset, word)) = queue.pop_front() {
        for generator in 0..table.generator_count() {
            let index = u8::try_from(generator).unwrap_or(u8::MAX);
            for step in [Letter::generator(index), Letter::inverse_of(index)] {
                let next = traced(table, coset, &Word::from_iter([step]));
                if !reached[next] {
                    reached[next] = true;
                    queue.push_back((next, word.letters().iter().copied().chain([step]).collect()));
                }
            }
        }
        order.push((coset, word));
    }
    order
}

#[expect(
    clippy::expect_used,
    reason = "the construction computed the foot of every mirror that is on with a call that returns a normalized point, and the centre mirror of a face is on or is the mirror through the generator point when only one is"
)]
fn kind_of(
    face: &Face,
    wythoff: &Wythoff,
    geometry: Geometry,
    vertices: &[DVec3],
    covectors: &[DVec3],
) -> Kind {
    let corner = face.corner;
    let after = (corner + 1) % 3;
    let order = wythoff.orders()[corner];
    let (centre_side, vertex_side, sides) = match face.cuts.as_slice() {
        [cut] => (cut.side, other_side(corner, cut.side), order),
        _ => (after, corner, 2 * order),
    };
    let foot = wythoff
        .foot(centre_side)
        .expect("internal error: the centre mirror of a face is on, so it has a foot");
    let normalized = match geometry {
        Geometry::Hyperbolic => hyperbolic::normalize_point(foot).ok(),
        Geometry::Spherical => spherical::normalize_point(foot).ok(),
        Geometry::Euclidean => Some(foot),
    }
    .expect("internal error: the foot of a mirror is a point of the plane, which normalizes");
    let turn = face_angle(geometry, vertices[corner], normalized);
    let radius = 1.0 / (2.0 * (PI / f64::from(sides)).sin());
    let polygon = flat_face(sides, turn, radius);
    let last = polygon.len() - 1;
    let generator_flat = if centre_side == after {
        polygon[0]
    } else {
        polygon[last]
    };
    let edge_zero = midpoint(&polygon, 0);
    let second = if face.cuts.len() == 1 {
        generator_flat
    } else {
        midpoint(&polygon, 1)
    };
    let centre_matrix = reflection(DVec2::ZERO, edge_zero);
    let vertex_matrix = reflection(DVec2::ZERO, second);
    let centre_letter = letter(centre_side);
    let (words, matrices) = stabilizer_elements(
        [centre_letter, letter(vertex_side)],
        [centre_matrix, vertex_matrix],
        order,
    );
    let generator = wythoff.generator();
    let foot_of = |side: usize| {
        wythoff
            .foot(side)
            .expect("internal error: a mirror that is on has a foot")
    };
    let oriented = |side: usize| {
        let sign = face
            .cuts
            .iter()
            .find(|cut| cut.side == side)
            .map(|cut| cut.sign)
            .expect("internal error: the perpendicular of a region side is a cut of its face");
        let perpendicular = wythoff
            .perpendicular(side)
            .expect("internal error: a cut of a face has a perpendicular");
        -sign * perpendicular
    };
    let centre = vertices[corner];
    let (points, flats, walls) = match face.cuts.len() {
        1 if centre_side == after => (
            vec![centre, foot_of(after), generator],
            vec![DVec2::ZERO, edge_zero, polygon[0]],
            vec![covectors[corner], covectors[after], oriented(after)],
        ),
        1 => (
            vec![centre, generator, foot_of(corner)],
            vec![DVec2::ZERO, polygon[last], edge_zero],
            vec![covectors[corner], covectors[after], oriented(corner)],
        ),
        _ => (
            vec![centre, foot_of(after), generator, foot_of(corner)],
            vec![DVec2::ZERO, edge_zero, polygon[0], second],
            vec![
                covectors[corner],
                covectors[after],
                oriented(after),
                oriented(corner),
            ],
        ),
    };
    Kind {
        corner,
        centre_side,
        vertex_side,
        radius,
        edge_starts: edge_starts(&polygon, &matrices, face.cuts.len()),
        words,
        matrices,
        centre_letter,
        turn,
        polygon,
        map: MaskMap::region(geometry, points, walls, flats),
        centre,
        foot: normalized,
    }
}

impl WholeFace {
    /// Returns the whole face of a Wythoff construction on its domain.
    ///
    /// The construction must have been built for the domain, and must be a
    /// regular tiling or have two or three face types. A regular tiling has
    /// one face type, at a corner of order at least 3 with one mirror through
    /// it on, on a triangle whose corner 2 has the order 2 and whose third
    /// corner an order of at least 3. These are the marks with only mark 1 on
    /// and with only mark 0 on, on the triangle `*pq2` with `p >= q >= 3`.
    /// Every other construction with one face type is refused. The whole face
    /// keeps the construction, the side presentation of the domain, for each
    /// face type the map from its part of the domain onto its part of the
    /// face mask, and the geometry, the centre of the reference face of each
    /// type, the midpoint of its edge 0, and the pairing of each side of the
    /// domain, from which it turns the face mask of each picture, and no
    /// reference to the domain.
    ///
    /// # Errors
    ///
    /// Returns an error of kind
    /// [`ErrorKind::InvalidOption`](crate::ErrorKind::InvalidOption), for the
    /// first of these causes: the construction holds other walls than the
    /// sides of the domain, the construction has one face type and is not a
    /// regular tiling, or the domain has no side presentation.
    pub fn new(domain: &FundamentalDomain, wythoff: Wythoff) -> Result<Self> {
        if !wythoff.fits(domain) {
            return Err(Error::other_construction());
        }
        let regular = wythoff.regular_face();
        if regular.is_none() && wythoff.faces().len() == 1 {
            return Err(Error::not_regular());
        }
        let presentation = domain
            .side_presentation()
            .map_err(|error| Error::no_presentation(error).during(WHOLE_FACE))?;
        Ok(match regular {
            Some((corner, order)) => Self::regular(domain, wythoff, presentation, corner, order),
            None => Self::several(domain, wythoff, presentation),
        })
    }

    fn regular(
        domain: &FundamentalDomain,
        wythoff: Wythoff,
        presentation: Presentation,
        corner: usize,
        order: u32,
    ) -> Self {
        let (centre_mirror, edge_side) = if corner == 0 { (0, 2) } else { (2, 0) };
        let vertices = domain.vertices();
        let geometry = domain.geometry();
        let turn = face_angle(geometry, vertices[corner], vertices[2]);
        let polygon = flat_face(order, turn, 1.0);
        let last = polygon.len() - 1;
        let mut triangle = [DVec2::ZERO; 3];
        triangle[2] = DVec2::from_angle(turn) * (PI / f64::from(order)).cos();
        triangle[1 - corner] = if corner == 0 {
            polygon[last]
        } else {
            polygon[0]
        };
        let centre_matrix = reflection(triangle[corner], triangle[2]);
        let vertex_matrix = reflection(triangle[corner], triangle[1 - corner]);
        let [centre_letter, vertex_letter, edge_letter] =
            [centre_mirror, VERTEX_MIRROR, edge_side].map(letter);
        let rotation = centre_matrix * vertex_matrix;
        let (words, matrices) = stabilizer_elements(
            [centre_letter, vertex_letter],
            [centre_matrix, vertex_matrix],
            order,
        );
        let towards_edge_1 = |matrix: DMat2| {
            (matrix * midpoint(&polygon, 0)).distance_squared(midpoint(&polygon, 1))
        };
        let (forward, backward) =
            if towards_edge_1(rotation) <= towards_edge_1(vertex_matrix * centre_matrix) {
                (
                    [centre_letter, vertex_letter],
                    [vertex_letter, centre_letter],
                )
            } else {
                (
                    [vertex_letter, centre_letter],
                    [centre_letter, vertex_letter],
                )
            };
        let edge_words = (0..polygon.len())
            .map(|edge| {
                let turn = |pair: [Letter; 2]| (0..edge).flat_map(move |_| pair);
                turn(forward)
                    .chain([edge_letter])
                    .chain(turn(backward))
                    .collect()
            })
            .collect();
        let map = MaskMap::onto(domain, triangle.to_vec());
        let mut corner_kinds = [None; 3];
        corner_kinds[corner] = Some(0);
        let stabilizer_order = words.len();
        let kind = Kind {
            corner,
            centre_side: centre_mirror,
            vertex_side: VERTEX_MIRROR,
            radius: 1.0,
            edge_starts: edge_starts(&polygon, &matrices, 1),
            words,
            matrices,
            centre_letter,
            turn,
            polygon,
            map,
            centre: vertices[corner],
            foot: vertices[2],
        };
        Self {
            wythoff: Box::new(wythoff),
            presentation,
            corner_kinds,
            types: vec![FaceType {
                corner: to_u32(corner),
                order,
                sides: order,
            }],
            stabilizer: kind.words.get(1..).unwrap_or_default().to_vec(),
            index: 2 * order,
            least: stabilizer_order,
            kinds: vec![kind],
            edge_words,
            geometry,
            pairings: domain.sides().iter().map(|side| side.pairing()).collect(),
        }
    }

    #[expect(
        clippy::expect_used,
        reason = "the least common multiple of at most three numbers of at most 200 is below 200 cubed, which fits u32"
    )]
    fn several(domain: &FundamentalDomain, wythoff: Wythoff, presentation: Presentation) -> Self {
        let geometry = domain.geometry();
        let vertices = domain.vertices();
        let covectors: Vec<DVec3> = domain.sides().iter().map(|side| side.covector()).collect();
        let kinds: Vec<Kind> = wythoff
            .faces()
            .iter()
            .map(|face| kind_of(face, &wythoff, geometry, vertices, &covectors))
            .collect();
        let mut corner_kinds = [None; 3];
        for (position, kind) in kinds.iter().enumerate() {
            corner_kinds[kind.corner] = Some(position);
        }
        let orders = wythoff.orders();
        let types = kinds
            .iter()
            .map(|kind| FaceType {
                corner: to_u32(kind.corner),
                order: orders[kind.corner],
                sides: to_u32(kind.polygon.len()),
            })
            .collect();
        let least = kinds.iter().fold(1, |least, kind| {
            least / greatest_common_divisor(least, kind.words.len()) * kind.words.len()
        });
        let stabilizer = kinds
            .iter()
            .flat_map(|kind| kind.words.iter().skip(1).cloned())
            .collect();
        Self {
            wythoff: Box::new(wythoff),
            presentation,
            kinds,
            corner_kinds,
            types,
            stabilizer,
            index: u32::try_from(least)
                .expect("internal error: the least index of a construction fits u32"),
            least,
            edge_words: Vec::new(),
            geometry,
            pairings: domain.sides().iter().map(|side| side.pairing()).collect(),
        }
    }

    /// Returns the side presentation of the domain, whose generator `j`
    /// stands for side `j`, which the search of the arrangements takes.
    #[must_use]
    pub fn presentation(&self) -> &Presentation {
        &self.presentation
    }

    /// Returns the elements of the stabilizers of the reference faces other
    /// than the identity, as words in the generators of the
    /// [`presentation`](WholeFace::presentation).
    ///
    /// For each face type, in the order of the corners, with `m` and `v` the
    /// two sides through its corner, the words are `(m v)^j` and `(m v)^j m`
    /// for `j` from 0 to `n - 1`, in the order of `j` with the rotation
    /// before the reflection, without the first, which is the empty word. On
    /// a regular tiling, `m` is the side through the centre of the face and
    /// corner 2, and `v` is side 1. With several face types, `m` is the side
    /// that is on when one side through the corner is on, and the side after
    /// the corner when both are. A reflection in a side through two corners
    /// with a face appears once for each of them.
    #[must_use]
    pub fn stabilizer(&self) -> &[Word] {
        &self.stabilizer
    }

    /// Returns the least number of colours of an arrangement, the least
    /// common multiple of the orders `2 n` of the stabilizers of the face
    /// types. On a regular tiling it is the number of colours of an
    /// arrangement with one picture. The number of colours of every
    /// arrangement is a multiple of it.
    #[must_use]
    pub fn index(&self) -> u32 {
        self.index
    }

    /// Returns the face types, in the order of the corners: one for a regular
    /// tiling, and two or three for a construction with several face types.
    #[must_use]
    pub fn face_types(&self) -> &[FaceType] {
        &self.types
    }

    /// Returns how the face across each edge of the reference face of each
    /// picture meets it, in an arrangement: one [`EdgeMeeting`] for each edge
    /// of each picture, in the order of the pictures and then of the edges,
    /// so that the edges of a picture follow those of every earlier picture.
    /// On a regular tiling with faces of `n` sides, edge `i` of picture `X` is
    /// at position `X n + i`.
    ///
    /// # Errors
    ///
    /// Returns an error of kind
    /// [`ErrorKind::InvalidOption`](crate::ErrorKind::InvalidOption), for the
    /// first of these causes: the table of the colouring has another number
    /// of generators than the domain has sides, a relator of the side
    /// presentation does not return some coset to itself, the number of
    /// colours of the colouring is not a multiple of
    /// [`index`](WholeFace::index), or the elements of the stabilizer of a
    /// face type do not carry the coset of each picture of that type to every
    /// coset once, so the colouring is not an arrangement.
    pub fn edges(&self, arrangement: &Colouring) -> Result<Vec<EdgeMeeting>> {
        Ok(self.read(arrangement, EDGE_PAIRING)?.edges)
    }

    /// Returns the face mask of one picture of an arrangement at the given
    /// size, with the pictures numbered from 0 over all face types.
    ///
    /// The mask shows the flat regular polygon of the picture, white on
    /// black, turned so that the direction from its centre toward edge 0
    /// agrees with the direction, in the default view of the geometry, from
    /// the centre of the reference face of the picture toward edge 0 of that
    /// face, which shows a painted picture the same way up there in the plane
    /// and in the disk, whatever the render options say, with the edges
    /// numbered counterclockwise. With one picture, the polygon is centred
    /// and fitted in the image as the polygon masks of
    /// [`Masks`](crate::Masks) are. With several, every mask of the
    /// arrangement takes the largest scale at which every one of its polygons
    /// fits its image, so that every edge of every mask has one length in
    /// pixels, and each polygon is centred in its image at that scale. On a
    /// construction with several face types every edge of every polygon has
    /// one length. Inside each edge it draws a border of 1/64 of the shorter
    /// side of the image in a code colour: two edges that meet share one, also
    /// on the masks of two different pictures, and an edge that meets itself
    /// has one of its own. The quarter of an edge at its marked end is black.
    /// The first edge of each pair, by picture and then by number, is marked
    /// at its start. Its partner is marked at its end when the neighbour is
    /// turned and at its start when it is mirrored, so the marked ends meet.
    /// An edge that meets itself with a turned neighbour is marked at both
    /// ends. A black tick at the midpoint of edge 0, as wide as the border is
    /// deep or a quarter of the edge where that is less, runs from the edge
    /// four border depths into the polygon, so that the edges can be counted
    /// from edge 0. The buffer holds 8-bit sRGB in the layout of
    /// [`Renderer::render`](crate::Renderer::render), each pixel the mean of
    /// a 4 by 4 grid of samples. The mask reads no render option and starts
    /// no thread.
    ///
    /// # Errors
    ///
    /// Returns the errors of [`edges`](WholeFace::edges) for the arrangement,
    /// then an error of kind
    /// [`ErrorKind::InvalidOption`](crate::ErrorKind::InvalidOption) for a
    /// picture at or above the number of pictures of the arrangement, and
    /// then the errors of
    /// [`RenderOptionsBuilder::size`](crate::RenderOptionsBuilder::size) for
    /// the size, with their kinds.
    pub fn render_mask(
        &self,
        arrangement: &Colouring,
        picture: u32,
        width: u32,
        height: u32,
    ) -> Result<Vec<u8>> {
        let reading = self.read(arrangement, FACE_MASK)?;
        let count = reading.pictures.len();
        let chosen = usize::try_from(picture)
            .ok()
            .filter(|&chosen| chosen < count)
            .ok_or_else(|| Error::mask_picture(picture, count))?;
        check_size(width, height).map_err(|error| error.during(FACE_MASK))?;
        let firsts = self.first_edges(&reading.pictures);
        let styles = face_mask_styles(&reading.edges, &firsts);
        let polygons = self.picture_polygons_of(&reading.pictures);
        let placement = Placement::arrangement(&polygons, width, height)[chosen];
        let polygon = &polygons[chosen];
        Ok(draw_mask(
            polygon,
            placement,
            &styles[firsts[chosen]..firsts[chosen] + polygon.len()],
            Tick::OnEdgeZero,
            width,
            height,
            MASK_GRID,
        ))
    }

    fn first_edges(&self, pictures: &[Picture]) -> Vec<usize> {
        pictures
            .iter()
            .scan(0, |first, picture| {
                let start = *first;
                *first += self.kinds[picture.kind].polygon.len();
                Some(start)
            })
            .collect()
    }

    fn picture_turn(&self, kind: &Kind, base: &Word) -> f64 {
        let carrying = base
            .letters()
            .iter()
            .fold(DMat3::IDENTITY, |total, letter| {
                let pairing = self.pairings[usize::from(letter.index())];
                let pairing = if letter.is_inverse() {
                    pairing.inverse()
                } else {
                    pairing
                };
                total * pairing
            });
        face_angle(self.geometry, carrying * kind.centre, carrying * kind.foot)
    }

    fn picture_polygons_of(&self, pictures: &[Picture]) -> Vec<Vec<DVec2>> {
        pictures
            .iter()
            .map(|picture| {
                let kind = &self.kinds[picture.kind];
                flat_face(
                    to_u32(kind.polygon.len()),
                    self.picture_turn(kind, &picture.base),
                    kind.radius,
                )
            })
            .collect()
    }

    #[expect(
        clippy::expect_used,
        reason = "the traversal visits every coset of a complete table, and each coset that it visits is held by an earlier picture of the face type or starts a picture whose elements include the empty word and the centre mirror, so every coset holds an element of each face type"
    )]
    fn read(&self, arrangement: &Colouring, operation: &'static str) -> Result<Reading> {
        check_colouring(&self.presentation, arrangement)
            .map_err(|error| error.during(operation))?;
        let table = arrangement.table();
        if !table.index().is_multiple_of(self.least) {
            return Err(Error::arrangement_size(table.index(), self.least).during(operation));
        }
        let order = reach_words(table);
        let mut pictures = Vec::new();
        let mut elements = Vec::with_capacity(self.kinds.len());
        for (position, kind) in self.kinds.iter().enumerate() {
            let mut held: Vec<Option<Element>> = vec![None; table.index()];
            for (coset, reach) in &order {
                if held[*coset].is_some() {
                    continue;
                }
                let picture = pictures.len();
                let base: Word = if reach.len() % 2 == 0 {
                    reach.clone()
                } else {
                    reach
                        .letters()
                        .iter()
                        .copied()
                        .chain([kind.centre_letter])
                        .collect()
                };
                let base_coset = traced(table, 0, &base);
                for (word, letters) in kind.words.iter().enumerate() {
                    let slot = &mut held[traced(table, base_coset, letters)];
                    if slot.is_some() {
                        return Err(Error::not_arrangement().during(operation));
                    }
                    *slot = Some(Element { picture, word });
                }
                pictures.push(Picture {
                    kind: position,
                    base,
                    coset: base_coset,
                });
            }
            elements.push(held.into_iter().collect::<Option<Vec<_>>>().expect(
                "internal error: every coset of a complete table holds an element of a picture of each face type",
            ));
        }
        let edges = if self.edge_words.is_empty() {
            self.meet_types(table, &pictures, &elements)
        } else {
            self.meet_edges(table, &pictures, &elements[0])
        };
        Ok(Reading {
            pictures,
            elements,
            edges,
        })
    }

    fn meet_edges(
        &self,
        table: &CosetTable,
        pictures: &[Picture],
        elements: &[Element],
    ) -> Vec<EdgeMeeting> {
        let kind = &self.kinds[0];
        let mut edges = Vec::with_capacity(pictures.len() * self.edge_words.len());
        for picture in pictures {
            for (edge, word) in self.edge_words.iter().enumerate() {
                let element = elements[traced(table, picture.coset, word)];
                let matrix = kind.matrices[element.word];
                let partner = nearest_edge(&kind.polygon, matrix * midpoint(&kind.polygon, edge));
                edges.push(EdgeMeeting {
                    picture: to_u32(element.picture),
                    partner: to_u32(partner),
                    mirrored: matrix.determinant() > 0.0,
                });
            }
        }
        edges
    }

    fn meet_types(
        &self,
        table: &CosetTable,
        pictures: &[Picture],
        elements: &[Vec<Element>],
    ) -> Vec<EdgeMeeting> {
        let mut edges = Vec::new();
        for picture in pictures {
            let kind = &self.kinds[picture.kind];
            for &(word, start) in &kind.edge_starts {
                let coset = traced(table, picture.coset, &kind.words[word]);
                let side = if start == 0 {
                    kind.centre_side
                } else {
                    kind.vertex_side
                };
                let ends = [(side + 2) % 3, side];
                let across = if ends[0] == kind.corner {
                    ends[1]
                } else {
                    ends[0]
                };
                let (other, element, other_start, sign) =
                    if let Some(position) = self.corner_kinds[across] {
                        let other = &self.kinds[position];
                        let other_start = usize::from(side != other.centre_side);
                        (other, elements[position][coset], other_start, 1.0)
                    } else {
                        let mirror = letter(other_side(across, side));
                        let beyond = traced(table, coset, &Word::from_iter([mirror]));
                        (kind, elements[picture.kind][beyond], start, -1.0)
                    };
                let matrix = other.matrices[element.word];
                let partner = nearest_edge(
                    &other.polygon,
                    matrix * midpoint(&other.polygon, other_start),
                );
                let turned = kind.matrices[word].determinant() * matrix.determinant() * sign;
                edges.push(EdgeMeeting {
                    picture: to_u32(element.picture),
                    partner: to_u32(partner),
                    mirrored: turned < 0.0,
                });
            }
        }
        edges
    }
}

pub(crate) fn face_mask_styles(edges: &[EdgeMeeting], firsts: &[usize]) -> Vec<EdgeStyle> {
    let meetings: Vec<Vec<usize>> = edges
        .iter()
        .map(|meeting| {
            let picture = usize::try_from(meeting.picture).unwrap_or(usize::MAX);
            let partner = usize::try_from(meeting.partner).unwrap_or(usize::MAX);
            vec![
                firsts
                    .get(picture)
                    .map_or(usize::MAX, |first| first.saturating_add(partner)),
            ]
        })
        .collect();
    let turned: Vec<bool> = edges.iter().map(|meeting| !meeting.mirrored).collect();
    seam_classes(&meetings, &turned)
}

/// A [`WholeFace`] with an arrangement and the picture that the faces of each
/// of its orbits show.
///
/// Build it with [`WholeFaceFill::new`] and render it as
/// [`Fill::WholeFace`](crate::Fill::WholeFace) with the domain of the whole
/// face. The renderer draws the faces and their borders as a
/// [`WythoffFill`](crate::WythoffFill) of the construction does. Inside a
/// face it carries the folded point of each sample onto the face mask of a
/// picture of the face type of the sample, by the map of the part of the
/// domain that belongs to that face type onto its part of the face mask,
/// followed by the turn or mirror of the element of its stabilizer that the
/// side sequence of the fold selects in the arrangement, and by the turn of
/// the face mask of the picture that it selects. A
/// [`Paint::Image`](crate::Paint::Image) is read where that point lies in the
/// face mask of its picture at the size of the image, so an image painted
/// over the face mask of a picture shows whole on every face of that
/// picture, turned or mirrored as the arrangement says. The reference face of
/// each picture shows it as its face mask does, and a solid paint gives every
/// face of its picture its colour.
///
/// # Examples
///
/// ```
/// use escher_domain::FundamentalDomain;
/// use escher_group::{SearchBudget, free_classes_of_index};
/// use escher_render::{Colour, Fill, Paint, RenderOptions, Renderer, WholeFace, WholeFaceFill, Wythoff};
/// use escher_signature::Signature;
///
/// let domain = FundamentalDomain::build(&"*732".parse::<Signature>()?)?;
/// let triangles = WholeFace::new(&domain, Wythoff::new(&domain, [true, false, false])?)?;
/// let found = free_classes_of_index(
///     triangles.presentation(),
///     triangles.stabilizer(),
///     3 * triangles.index(),
///     SearchBudget::DEFAULT,
/// )?;
/// let arrangement = found.list().first().ok_or("no arrangement")?.clone();
/// let paints = [(233, 196, 106), (42, 157, 143), (231, 111, 81)]
///     .map(|(red, green, blue)| Paint::Solid(Colour::from_srgb8(red, green, blue)));
/// let fill = WholeFaceFill::new(triangles, arrangement, paints.to_vec())?;
/// let options = RenderOptions::builder(Fill::WholeFace(fill)).size(32, 32).build()?;
/// let (_, stats) = Renderer::new(&domain, options)?.render();
/// assert_eq!(stats.unconverged(), 0);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
#[derive(Clone, Debug, PartialEq)]
pub struct WholeFaceFill {
    face: Box<WholeFace>,
    arrangement: Colouring,
    elements: Vec<Vec<(usize, DMat2)>>,
    turns: Vec<DMat2>,
    paints: Vec<Paint>,
    placements: Vec<Option<Placement>>,
    linear: Box<[f64; 256]>,
}

impl WholeFaceFill {
    /// Returns the fill that shows `paints` on the faces in the arrangement,
    /// with one paint for each picture of the arrangement, in the order of
    /// the pictures: A, B, C, and so on on a regular tiling, and with several
    /// face types the pictures of each type in the order of the corners.
    ///
    /// # Errors
    ///
    /// Returns the errors of [`WholeFace::edges`] for the arrangement, and
    /// then an error of kind
    /// [`ErrorKind::InvalidOption`](crate::ErrorKind::InvalidOption) when
    /// `paints` does not hold exactly one paint for each picture.
    pub fn new(face: WholeFace, arrangement: Colouring, paints: Vec<Paint>) -> Result<Self> {
        let reading = face.read(&arrangement, WHOLE_FACE_FILL)?;
        if paints.len() != reading.pictures.len() {
            return Err(Error::paint_count(reading.pictures.len(), paints.len()));
        }
        let elements = reading
            .elements
            .iter()
            .zip(&face.kinds)
            .map(|(elements, kind)| {
                elements
                    .iter()
                    .map(|element| (element.picture, kind.matrices[element.word]))
                    .collect()
            })
            .collect();
        let turns = reading
            .pictures
            .iter()
            .map(|picture| {
                let kind = &face.kinds[picture.kind];
                DMat2::from_angle(face.picture_turn(kind, &picture.base) - kind.turn)
            })
            .collect();
        let polygons = face.picture_polygons_of(&reading.pictures);
        let placements = paints
            .iter()
            .enumerate()
            .map(|(picture, paint)| match paint {
                Paint::Image(image) => {
                    Some(Placement::arrangement(&polygons, image.width(), image.height())[picture])
                }
                Paint::Solid(_) => None,
            })
            .collect();
        Ok(Self {
            face: Box::new(face),
            arrangement,
            elements,
            turns,
            paints,
            placements,
            linear: Box::new(decode_table()),
        })
    }

    pub(crate) fn wythoff(&self) -> &Wythoff {
        &self.face.wythoff
    }

    #[expect(
        clippy::expect_used,
        reason = "the renderer uses a whole-face fill only with a domain of its construction, whose sides are the generators of the table and whose face types are those of the fill, and the fill holds a picture and a matrix for each coset and face type"
    )]
    pub(crate) fn picture(
        &self,
        face: usize,
        sides: &[u8],
        point: DVec3,
    ) -> Option<(usize, DVec2)> {
        let table = self.arrangement.table();
        let &(picture, matrix) = sides
            .iter()
            .try_fold(0, |coset, &side| table.image(coset, Letter::generator(side)))
            .and_then(|coset| usize::try_from(coset).ok())
            .and_then(|coset| self.elements.get(face)?.get(coset))
            .expect("internal error: every side sequence of the domain of a whole-face fill reaches a coset");
        let flat = matrix * self.face.kinds[face].map.as_ref()?.map(point)?;
        Some((picture, self.turns[picture] * flat))
    }

    pub(crate) fn value(
        &self,
        face: usize,
        sides: &[u8],
        point: DVec3,
        background: Colour,
    ) -> Colour {
        let Some((picture, at)) = self.picture(face, sides, point) else {
            return background;
        };
        match &self.paints[picture] {
            Paint::Solid(colour) => *colour,
            Paint::Image(image) => self.placements[picture]
                .and_then(|placement| placement.inside(placement.position(at)))
                .map_or(background, |position| {
                    Colour::from_linear(sample(image, position, background.linear(), &self.linear))
                }),
        }
    }
}

