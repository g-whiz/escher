    struct Scene {
        name: String,
        text: &'static str,
        marks: [bool; 3],
        domain: FundamentalDomain,
        face: WholeFace,
        corner: usize,
        arrangements: Vec<Colouring>,
    }

    impl Scene {
        fn new(
            text: &'static str,
            marks: [bool; 3],
            arrangements: &dyn Fn(&WholeFace) -> Vec<Colouring>,
        ) -> Self {
            let domain = domain_with_settings(text, &[]);
            let face = whole_face(&domain, marks);
            Self {
                name: format!("{text} {}", marks_text(marks)),
                text,
                marks,
                arrangements: arrangements(&face),
                domain,
                face,
                corner: face_corner(marks),
            }
        }

        fn order(&self) -> usize {
            usize::try_from(self.face.types[0].order).unwrap_or(usize::MAX)
        }
    }

    fn scenes(set: &[(&'static str, [bool; 3])], pictures: &[u32]) -> Vec<Scene> {
        set.iter()
            .map(|&(text, marks)| {
                Scene::new(text, marks, &|face| {
                    pictures
                        .iter()
                        .flat_map(|&count| arrangements_with(face, count))
                        .collect()
                })
            })
            .collect()
    }

    fn picture_set() -> Vec<Scene> {
        scenes(&WHOLE_FACE_SET, &PICTURE_COUNTS)
    }

    fn crowded_set() -> Vec<Scene> {
        SEVERAL_PICTURES
            .iter()
            .chain([&FOUR_PICTURES])
            .map(|tiling| {
                let order = signature_orders(tiling.signature)[face_corner(tiling.marks)];
                let counts: Vec<u32> = (4..=IndexLimit::DEFAULT.get())
                    .filter(|count| 2 * order * count <= IndexLimit::MAX.get())
                    .collect();
                Scene::new(tiling.signature, tiling.marks, &|face| {
                    counts
                        .iter()
                        .flat_map(|&count| arrangements_with(face, count))
                        .collect()
                })
            })
            .collect()
    }

    fn words(face: &WholeFace) -> Vec<Word> {
        face.kinds[0].words.clone()
    }

    fn largest_entry(reference: &mut Reference, first: &Matrix, second: &Matrix) -> f64 {
        (0..3)
            .map(|row| {
                let gap = difference(&first[row], &second[row]);
                reference.approximate(&largest_magnitude(&gap))
            })
            .fold(0.0, f64::max)
    }

    fn gap(reference: &mut Reference, first: &Vector, second: &Vector) -> f64 {
        reference.approximate(&largest_magnitude(&difference(first, second)))
    }

    fn determinant(matrix: &Matrix) -> BigFloat {
        let column = |index: usize| [0, 1, 2].map(|row| matrix[row][index].clone());
        dot(&column(0), &cross(&column(1), &column(2)))
    }

    fn exact_vertices(domain: &FundamentalDomain) -> Vec<Vector> {
        domain
            .vertices()
            .iter()
            .map(|vertex| vector(vertex.to_array()))
            .collect()
    }

    fn signature_text(orders: [u32; 3]) -> String {
        orders
            .iter()
            .map(|&order| {
                if order < 10 {
                    order.to_string()
                } else {
                    format!("({order})")
                }
            })
            .collect()
    }

    fn on_surface(measure: Measure, centre: &Vector, weights: &[(u32, &Vector)]) -> Vector {
        let sum = weights
            .iter()
            .fold([int(0), int(0), int(0)], |total, (weight, point)| {
                let scaled = scale(&int(*weight), point);
                [0, 1, 2].map(|index| escher_reference::add(&total[index], &scaled[index]))
            });
        oriented(measure, centre, &sum)
    }

    fn several_table(orders: [u32; 3], marks: [bool; 3]) -> Option<usize> {
        let text = marks_text(marks);
        let (two, three): (&[&str], &[&str]) = match orders {
            [_, 2, 2] if orders[0] == 2 => (&[], &["111"]),
            [_, 2, 2] => (&["110", "101"], &["111"]),
            [_, second, 2] if second >= 3 => (&["001", "101", "011"], &["110", "111"]),
            _ => (&["100", "010", "001"], &["110", "101", "011", "111"]),
        };
        if two.contains(&text.as_str()) {
            Some(2)
        } else if three.contains(&text.as_str()) {
            Some(3)
        } else {
            None
        }
    }

    #[test]
    fn whole_face_accepts_the_regular_tilings_and_the_constructions_of_several_face_types() {
        let mut accepted = Vec::new();
        let mut several = Vec::new();
        let mut refused_by_one = [0; 4];
        for text in WYTHOFF_DOMAINS {
            let domain = domain_with_settings(text, &[]);
            let orders = signature_orders(text);
            let [first, second, third] = orders;
            let turned: [&str; 3] = [
                &format!("*{}", signature_text([second, third, first])),
                &format!("*{}", signature_text([third, first, second])),
                &format!("*{}", signature_text([first, third, second])),
            ];
            for spelling in turned {
                assert_eq!(signature_orders(spelling), orders, "{spelling}");
            }
            for marks in MARKINGS {
                let Ok(wythoff) = Wythoff::new(&domain, marks) else {
                    assert_eq!(several_table(orders, marks), None, "{text} {marks:?}");
                    continue;
                };
                let types = several_table(orders, marks);
                let conditions = [
                    marks == REGULAR || marks == DUAL,
                    third == 2,
                    second >= 3,
                    first >= second,
                ];
                let regular = conditions.iter().all(|&condition| condition);
                if types.is_none()
                    && let [failed] = conditions
                        .iter()
                        .enumerate()
                        .filter(|(_, condition)| !**condition)
                        .map(|(index, _)| index)
                        .collect::<Vec<_>>()[..]
                {
                    refused_by_one[failed] += 1;
                }
                match (WholeFace::new(&domain, wythoff), types) {
                    (Ok(face), None) => {
                        assert!(regular, "{text} {marks:?} is accepted");
                        assert_regular_accessors(&face, &domain, text, marks);
                        accepted.push((text, marks));
                    }
                    (Ok(face), Some(count)) => {
                        assert_several_accessors(&face, text, marks, count);
                        several.push((text, marks));
                    }
                    (Err(error), None) => {
                        assert!(!regular, "{text} {marks:?} is refused: {error}");
                        assert_eq!(
                            (error.kind(), error.to_string()),
                            (
                                ErrorKind::InvalidOption,
                                "cannot build whole face: the construction is not a regular tiling"
                                    .to_owned()
                            )
                        );
                    }
                    (Err(error), Some(_)) => panic!("{text} {marks:?} is refused: {error}"),
                }
            }
        }
        assert_eq!(accepted.len(), 18, "{accepted:?}");
        println!("{} constructions of several face types", several.len());
        assert_eq!(several.len(), 79, "{several:?}");
        println!("refused by one condition alone (marks, corner 2, q, p >= q): {refused_by_one:?}");
        assert_eq!(refused_by_one, [0, 0, 4, 0]);
    }

    fn assert_regular_accessors(
        face: &WholeFace,
        domain: &FundamentalDomain,
        text: &str,
        marks: [bool; 3],
    ) {
        let name = format!("{text} {}", marks_text(marks));
        let corner = face_corner(marks);
        let order = signature_orders(text)[corner];
        assert_eq!(face.index(), 2 * order, "{name}");
        let types: Vec<(u32, u32, u32)> = face
            .face_types()
            .iter()
            .map(|kind| (kind.corner(), kind.order(), kind.sides()))
            .collect();
        let corner_number = u32::try_from(corner).expect("a corner of a triangle is below 3");
        assert_eq!(types, [(corner_number, order, order)], "{name}");
        let (elements, _) = stabilizer_words(centre_mirror(corner), 1, order);
        assert_eq!(face.stabilizer(), &elements[1..], "{name}");
        let presentation = domain
            .side_presentation()
            .unwrap_or_else(|error| panic!("{name}: {error}"));
        assert_eq!(face.presentation(), &presentation, "{name}");
    }

    fn assert_several_accessors(face: &WholeFace, text: &str, marks: [bool; 3], count: usize) {
        let name = format!("{text} {}", marks_text(marks));
        let rules = type_rules(signature_orders(text), marks);
        assert_eq!(rules.len(), count, "{name}");
        let types: Vec<(u32, u32, u32)> = face
            .face_types()
            .iter()
            .map(|kind| (kind.corner(), kind.order(), kind.sides()))
            .collect();
        let wanted: Vec<(u32, u32, u32)> = rules
            .iter()
            .map(|rule| {
                (
                    u32::try_from(rule.corner).unwrap_or(u32::MAX),
                    rule.order,
                    rule.sides,
                )
            })
            .collect();
        assert_eq!(types, wanted, "{name}");
        let least = rules.iter().fold(1, |least, rule| {
            let size = 2 * rule.order;
            let (mut a, mut b) = (least, size);
            while b != 0 {
                (a, b) = (b, a % b);
            }
            least / a * size
        });
        assert_eq!(face.index(), least, "{name}");
        let words: Vec<Word> = rules
            .iter()
            .flat_map(|rule| rule.words().into_iter().skip(1))
            .collect();
        assert_eq!(face.stabilizer(), words.as_slice(), "{name}");
    }

    struct Stabilized {
        text: &'static str,
        face: WholeFace,
        walls: Vec<crate::reference::Wall>,
        measure: Measure,
        corner: usize,
        vertices: Vec<Vector>,
        matrices: Vec<Matrix>,
        domain_centre: Vector,
        exact: ExactFace,
    }

    impl Stabilized {
        fn new(reference: &mut Reference, text: &'static str, marks: [bool; 3]) -> Self {
            let domain = domain_with_settings(text, &[]);
            let exact = exact_face(reference, text, &domain, marks);
            let face = whole_face(&domain, marks);
            let walls = reference_walls(&domain);
            let words = words(&face);
            assert_eq!(
                words.len(),
                2 * usize::try_from(face.types[0].order).unwrap_or(0),
                "{text}"
            );
            assert!(words[0].is_empty(), "{text}");
            let matrices = words.iter().map(|word| word_matrix(&walls, word)).collect();
            Self {
                text,
                walls,
                measure: Measure::of(domain.geometry()),
                corner: face_corner(marks),
                vertices: exact_vertices(&domain),
                matrices,
                domain_centre: vector(domain.centre().to_array()),
                face,
                exact,
            }
        }

        fn centre(&self) -> &Vector {
            &self.vertices[self.corner]
        }

        fn check_elements(&self, reference: &mut Reference) {
            let text = self.text;
            let centre = self.centre();
            let images: Vec<Vector> = self
                .matrices
                .iter()
                .map(|matrix| apply(matrix, &self.domain_centre))
                .collect();
            let radius = self.measure.distance(reference, centre, &images[0]);
            let radius = reference.approximate(&radius);
            for (first, matrix) in self.matrices.iter().enumerate() {
                let moved = apply(matrix, centre);
                assert!(
                    gap(reference, &moved, centre) <= FIXED,
                    "{text}: word {first} moves the centre"
                );
                let distance = self.measure.distance(reference, centre, &images[first]);
                let distance = reference.approximate(&distance);
                assert!(
                    (distance - radius).abs() <= FIXED,
                    "{text}: image {first} at {distance}, not {radius}"
                );
                for second in 0..first {
                    assert!(
                        largest_entry(reference, matrix, &self.matrices[second]) > DISTINCT,
                        "{text}: words {second} and {first} have one matrix"
                    );
                    let apart = self
                        .measure
                        .distance(reference, &images[first], &images[second]);
                    assert!(
                        reference.approximate(&apart) > DISTINCT,
                        "{text}: images {second} and {first} coincide"
                    );
                    let flat_gap = flat_gap(
                        reference,
                        &self.exact.elements[first].flat,
                        &self.exact.elements[second].flat,
                    );
                    assert!(
                        flat_gap > DISTINCT,
                        "{text}: words {second} and {first} have one flat matrix, {flat_gap:e} apart"
                    );
                }
                let code = self.face.kinds[0].matrices[first];
                let code: FlatMatrix = [
                    [num(code.x_axis.x), num(code.y_axis.x)],
                    [num(code.x_axis.y), num(code.y_axis.y)],
                ];
                let gap = flat_gap(reference, &code, &self.exact.elements[first].flat);
                assert!(
                    gap <= FIXED,
                    "{text}: the flat matrix of word {first} is {gap:e} from the reference"
                );
            }
        }

        fn count_inside(&self, reference: &mut Reference) -> usize {
            let centre = self.centre();
            let edge_walls: Vec<Vector> = self
                .face
                .edge_words
                .iter()
                .map(|word| {
                    let turns = &word.letters()[..(word.len() - 1) / 2];
                    let back: Word = turns.iter().copied().collect::<Word>().inverse();
                    transpose_apply(
                        &word_matrix(&self.walls, &back),
                        &self.walls[edge_side(self.corner)].covector,
                    )
                })
                .collect();
            let mut inside = 0;
            for (first, second, third) in weights() {
                let point = on_surface(
                    self.measure,
                    centre,
                    &[
                        (first, &self.vertices[0]),
                        (second, &self.vertices[1]),
                        (third, &self.vertices[2]),
                    ],
                );
                for matrix in &self.matrices {
                    let image = apply(matrix, &point);
                    let holds = edge_walls.iter().all(|wall| {
                        let side = escher_reference::mul(&dot(wall, &image), &dot(wall, centre));
                        reference.approximate(&side) >= -ON_WALL
                    });
                    assert!(
                        holds,
                        "{}: an image of the domain leaves the face",
                        self.text
                    );
                    inside += 1;
                }
            }
            inside
        }

        fn count_covered(&self, reference: &mut Reference) -> usize {
            let centre = self.centre();
            let inverses: Vec<Vec<Vector>> = words(&self.face)
                .iter()
                .map(|word| {
                    let back = word_matrix(&self.walls, &word.inverse());
                    self.walls
                        .iter()
                        .map(|wall| transpose_apply(&back, &wall.covector))
                        .collect()
                })
                .collect();
            let corners: Vec<Vector> = self
                .matrices
                .iter()
                .map(|matrix| apply(matrix, &self.vertices[1 - self.corner]))
                .collect();
            let mut covered = 0;
            for (index, first) in corners.iter().enumerate() {
                for second in &corners[..index] {
                    for (weight, near, far) in
                        [(1, 1, 1), (2, 1, 1), (1, 3, 1), (4, 1, 2), (1, 1, 5)]
                    {
                        let point = on_surface(
                            self.measure,
                            centre,
                            &[(weight, centre), (near, first), (far, second)],
                        );
                        let values: Vec<Vec<f64>> = inverses
                            .iter()
                            .map(|covectors| {
                                covectors
                                    .iter()
                                    .map(|covector| reference.approximate(&dot(covector, &point)))
                                    .collect()
                            })
                            .collect();
                        if values.iter().flatten().any(|value| value.abs() <= ON_WALL) {
                            continue;
                        }
                        let holding = values
                            .iter()
                            .filter(|sides| sides.iter().all(|&value| value < 0.0))
                            .count();
                        assert_eq!(
                            holding, 1,
                            "{}: a point of the face lies in {holding} images of the domain",
                            self.text
                        );
                        covered += 1;
                    }
                }
            }
            covered
        }
    }

    fn flat_gap(reference: &mut Reference, first: &FlatMatrix, second: &FlatMatrix) -> f64 {
        (0..2)
            .flat_map(|row| (0..2).map(move |column| (row, column)))
            .map(|(row, column)| {
                let gap = escher_reference::sub(&first[row][column], &second[row][column]);
                reference.approximate(&gap).abs()
            })
            .fold(0.0, f64::max)
    }

