    const EDGE_SIZE: u32 = 512;

    const EDGE_LENGTH_TOLERANCE: f64 = 1.0;

    const SCAN_OUTWARD: u32 = 6;

    const SCAN_INWARD: u32 = 3;

    const REFINEMENTS: usize = 3;

    const COARSE_BAND: f64 = 12.0;

    const TICK_CLEAR: [f64; 2] = [0.33, 0.67];

    fn non_black(pixel: &[u8]) -> bool {
        pixel.iter().any(|&channel| channel > 24)
    }

    fn mask_pixel(pixels: &[u8], size: u32, [column, row]: [u32; 2]) -> Option<&[u8]> {
        (column < size && row < size).then(|| {
            let offset = usize::try_from(3 * (row * size + column)).unwrap_or(usize::MAX);
            &pixels[offset..offset + 3]
        })
    }

    fn pixel_centre(column: u32, row: u32) -> DVec2 {
        DVec2::new(f64::from(column) + 0.5, f64::from(row) + 0.5)
    }

    fn count_f64(count: usize) -> f64 {
        f64::from(u32::try_from(count).unwrap_or(u32::MAX))
    }

    fn rough_corners(pixels: &[u8], size: u32, sides: usize) -> Vec<DVec2> {
        let inside: Vec<DVec2> = (0..size * size)
            .filter_map(|index| {
                let (column, row) = (index % size, index / size);
                mask_pixel(pixels, size, [column, row])
                    .filter(|pixel| non_black(pixel))
                    .map(|_| pixel_centre(column, row))
            })
            .collect();
        let centre = inside.iter().sum::<DVec2>() / count_f64(inside.len());
        let far = inside
            .iter()
            .copied()
            .max_by(|first, second| first.distance(centre).total_cmp(&second.distance(centre)))
            .unwrap_or(centre);
        let reach = far.distance(centre);
        let first = (far - centre).to_angle();
        (0..sides)
            .map(|corner| {
                let angle = first + core::f64::consts::TAU * count_f64(corner) / count_f64(sides);
                centre + reach * DVec2::from_angle(angle)
            })
            .collect()
    }

    fn fitted_line(points: &[DVec2]) -> (DVec2, DVec2) {
        let mean = points.iter().sum::<DVec2>() / count_f64(points.len());
        let [xx, xy, yy] = points.iter().fold([0.0; 3], |[xx, xy, yy], &point| {
            let offset = point - mean;
            [
                xx + offset.x * offset.x,
                xy + offset.x * offset.y,
                yy + offset.y * offset.y,
            ]
        });
        (mean, DVec2::from_angle(0.5 * (2.0 * xy).atan2(xx - yy)))
    }

    fn linear(byte: u8) -> f64 {
        let value = f64::from(byte) / 255.0;
        if value <= 0.040_45 {
            value / 12.92
        } else {
            ((value + 0.055) / 1.055).powf(2.4)
        }
    }

    fn crossing(
        pixels: &[u8],
        size: u32,
        line: [i64; 2],
        cross: f64,
        outside_low: bool,
    ) -> Option<f64> {
        let base = crate::golden_images::texel_index(cross, size);
        let [outward, inward] = [SCAN_OUTWARD, SCAN_INWARD];
        let (first, last) = if outside_low {
            (base.checked_sub(outward)?, base + inward)
        } else {
            (base.checked_sub(inward)?, base + outward)
        };
        let at = |position: u32| {
            let [across, down] = line;
            let [column, row] = if across < 0 {
                [position, u32::try_from(down).ok()?]
            } else {
                [u32::try_from(across).ok()?, position]
            };
            mask_pixel(pixels, size, [column, row])
        };
        let [outer, inner] = if outside_low {
            [at(first)?, at(last)?]
        } else {
            [at(last)?, at(first)?]
        };
        let coded = non_black(inner) && inner.iter().any(|&channel| channel < 200);
        if non_black(outer) || !coded {
            return None;
        }
        let channel = (0..3).max_by_key(|&channel| inner[channel])?;
        let full = linear(inner[channel]);
        let mut covered = 0.0;
        for position in first..=last {
            covered += (linear(at(position)?[channel]) / full).clamp(0.0, 1.0);
        }
        Some(if outside_low {
            f64::from(last) + 1.0 - covered
        } else {
            f64::from(first) + covered
        })
    }

    fn outline(pixels: &[u8], size: u32) -> Vec<(DVec2, Vec<DVec2>)> {
        (0..size * size)
            .filter_map(|index| {
                let (column, row) = (index % size, index / size);
                let pixel = mask_pixel(pixels, size, [column, row])?;
                let coded = non_black(pixel) && pixel.iter().any(|&channel| channel < 200);
                let steps: Vec<DVec2> = [(1, 0), (-1, 0), (0, 1), (0, -1)]
                    .into_iter()
                    .filter(|&(across, down)| {
                        column
                            .checked_add_signed(across)
                            .zip(row.checked_add_signed(down))
                            .and_then(|(column, row)| mask_pixel(pixels, size, [column, row]))
                            .is_some_and(|pixel| !non_black(pixel))
                    })
                    .map(|(across, down)| DVec2::new(f64::from(across), f64::from(down)))
                    .collect();
                (coded && !steps.is_empty()).then(|| (pixel_centre(column, row), steps))
            })
            .collect()
    }

    fn corners_of(lines: &[(DVec2, DVec2)]) -> Vec<DVec2> {
        let sides = lines.len();
        let meet = |(first, along): (DVec2, DVec2), (second, other): (DVec2, DVec2)| {
            first + (second - first).perp_dot(other) / along.perp_dot(other) * along
        };
        (0..sides)
            .map(|edge| meet(lines[(edge + sides - 1) % sides], lines[edge]))
            .collect()
    }

    fn coarse_corners(pixels: &[u8], size: u32, sides: usize) -> Vec<DVec2> {
        let rough = rough_corners(pixels, size, sides);
        let rough_centre = rough.iter().sum::<DVec2>() / count_f64(sides);
        let outline = outline(pixels, size);
        let lines: Vec<(DVec2, DVec2)> = (0..sides)
            .map(|edge| {
                let (start, end) = (rough[edge], rough[(edge + 1) % sides]);
                let run = end - start;
                let outward = DVec2::new(run.y, -run.x).normalize();
                let outward = if outward.dot(start - rough_centre) < 0.0 {
                    -outward
                } else {
                    outward
                };
                let chosen: Vec<DVec2> = outline
                    .iter()
                    .filter(|(_, steps)| steps.iter().any(|step| step.dot(outward) > 0.3))
                    .map(|&(point, _)| point)
                    .filter(|&point| {
                        let fraction = (point - start).dot(run) / run.length_squared();
                        let off = run.perp_dot(point - start).abs() / run.length();
                        off < COARSE_BAND
                            && (0.25..=0.75).contains(&fraction)
                            && !(TICK_CLEAR[0]..=TICK_CLEAR[1]).contains(&fraction)
                    })
                    .collect();
                assert!(
                    chosen.len() >= 2,
                    "edge {edge} has {} outline pixels",
                    chosen.len()
                );
                fitted_line(&chosen)
            })
            .collect();
        corners_of(&lines)
    }

    fn measured_edges(pixels: &[u8], size: u32, sides: usize) -> Vec<f64> {
        let mut corners = coarse_corners(pixels, size, sides);
        for _ in 0..REFINEMENTS {
            corners = refined_corners(pixels, size, &corners);
        }
        (0..sides)
            .map(|edge| corners[edge].distance(corners[(edge + 1) % sides]))
            .collect()
    }

    fn refined_corners(pixels: &[u8], size: u32, rough: &[DVec2]) -> Vec<DVec2> {
        let sides = rough.len();
        let rough_centre = rough.iter().sum::<DVec2>() / count_f64(sides);
        let lines: Vec<(DVec2, DVec2)> = (0..sides)
            .map(|edge| {
                let (start, end) = (rough[edge], rough[(edge + 1) % sides]);
                let run = end - start;
                let steep = run.y.abs() > run.x.abs();
                let mut points = Vec::new();
                for scan in 0..size {
                    let at = f64::from(scan) + 0.5;
                    let (fraction, cross) = if steep {
                        (
                            (at - start.y) / run.y,
                            start.x + (at - start.y) / run.y * run.x,
                        )
                    } else {
                        (
                            (at - start.x) / run.x,
                            start.y + (at - start.x) / run.x * run.y,
                        )
                    };
                    let length = run.length();
                    let depth = f64::from(size) / 64.0;
                    let slant = if steep { run.x.abs() } else { run.y.abs() } / length;
                    let clear = f64::from(SCAN_INWARD + 1) * slant / length;
                    let tick = depth.min(length / 4.0) / (2.0 * length) + clear;
                    if !(0.25 + clear..=0.75 - clear).contains(&fraction)
                        || (fraction - 0.5).abs() <= tick
                    {
                        continue;
                    }
                    let inward = if steep {
                        rough_centre.x > cross
                    } else {
                        rough_centre.y > cross
                    };
                    let line = if steep {
                        [-1, i64::from(scan)]
                    } else {
                        [i64::from(scan), -1]
                    };
                    if let Some(found) = crossing(pixels, size, line, cross, inward) {
                        points.push(if steep {
                            DVec2::new(found, at)
                        } else {
                            DVec2::new(at, found)
                        });
                    }
                }
                assert!(
                    points.len() >= 2,
                    "edge {edge} has {} crossings",
                    points.len()
                );
                fitted_line(&points)
            })
            .collect();
        corners_of(&lines)
    }

