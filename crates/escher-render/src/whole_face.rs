    const STABILIZER_MARGIN: f64 = 1e-9;

    const REGION_WEIGHTS: [[u32; 4]; 6] = [
        [1, 1, 1, 1],
        [4, 1, 1, 1],
        [1, 4, 1, 1],
        [1, 1, 4, 1],
        [1, 1, 1, 4],
        [2, 3, 1, 5],
    ];

    const FACE_WEIGHTS: [[u32; 3]; 5] = [[1, 1, 1], [5, 1, 1], [1, 5, 2], [2, 1, 5], [1, 3, 3]];

    fn approximate(reference: &mut Reference, point: &Vector) -> DVec3 {
        DVec3::from_array(point.each_ref().map(|value| reference.approximate(value)))
    }

    fn region_of(exact: &ExactWythoff, rule: TypeRule) -> Vec<Vector> {
        let after = (rule.corner + 1) % 3;
        let foot = |side: usize| {
            exact.feet[side]
                .clone()
                .unwrap_or_else(|| panic!("side {side} has no foot"))
        };
        let centre = exact.vertices[rule.corner].clone();
        let generator = exact.generator.clone();
        if rule.both() {
            vec![centre, foot(after), generator, foot(rule.corner)]
        } else if rule.centre == after {
            vec![centre, foot(after), generator]
        } else {
            vec![centre, generator, foot(rule.corner)]
        }
    }

    fn side_value(start: DVec3, end: DVec3, point: DVec3) -> f64 {
        let normal = start.cross(end);
        normal.dot(point) / (normal.length() * point.length())
    }

    fn least_side(polygon: &[DVec3], point: DVec3, orientation: f64) -> f64 {
        (0..polygon.len())
            .map(|side| {
                let start = polygon[(side + polygon.len() - 1) % polygon.len()];
                orientation * side_value(start, polygon[side], point)
            })
            .fold(f64::INFINITY, f64::min)
    }

    fn chart_angle(geometry: Geometry, centre: DVec3, first: DVec3, point: DVec3) -> f64 {
        let (normal, chart): (DVec3, Box<dyn Fn(DVec3) -> DVec3>) = match geometry {
            Geometry::Spherical => (centre, Box::new(move |point| point / centre.dot(point))),
            Geometry::Euclidean | Geometry::Hyperbolic => {
                (DVec3::Z, Box::new(|point: DVec3| point / point.z))
            }
        };
        let [first, point] = [first, point].map(|point| chart(point) - chart(centre));
        first
            .cross(point)
            .dot(normal)
            .atan2(first.dot(point))
            .rem_euclid(core::f64::consts::TAU)
    }

    fn surface_point(
        measure: Measure,
        centre: &Vector,
        points: &[Vector],
        weights: &[u32],
    ) -> Vector {
        let sum =
            points
                .iter()
                .zip(weights)
                .fold([int(0), int(0), int(0)], |total, (point, &weight)| {
                    let scaled = scale(&int(weight), point);
                    [0, 1, 2].map(|index| escher_reference::add(&total[index], &scaled[index]))
                });
        oriented(measure, centre, &sum)
    }

    #[test]
    #[expect(
        clippy::too_many_lines,
        reason = "the test checks the matrices, the face, the images of the region, and the cover of the face of every type in one pass"
    )]
    fn each_face_type_has_a_stabilizer_that_fixes_its_corner_and_covers_its_face_with_its_region() {
        let mut reference = Reference::new();
        let (mut types, mut inside, mut covered) = (0, 0, 0);
        for &(text, marks) in &SEVERAL_SET {
            let (domain, face) = several_face(text, marks);
            let geometry = domain.geometry();
            let measure = Measure::of(geometry);
            let walls = reference_walls(&domain);
            let exact = exact_wythoff(&domain, marks);
            let domain_centre = vector(domain.centre().to_array());
            for (kind, rule) in type_rules(signature_orders(text), marks)
                .into_iter()
                .enumerate()
            {
                let name = format!("{text} {} type {}", marks_text(marks), rule.corner);
                let matrices: Vec<Matrix> = rule
                    .words()
                    .iter()
                    .map(|word| word_matrix(&walls, word))
                    .collect();
                let corner = &exact.vertices[rule.corner];
                for (first, matrix) in matrices.iter().enumerate() {
                    let moved = apply(matrix, corner);
                    let off =
                        reference.approximate(&largest_magnitude(&difference(&moved, corner)));
                    assert!(
                        off <= STABILIZER_FIXED,
                        "{name}: word {first} moves the corner by {off:e}"
                    );
                    for (second, other) in matrices.iter().enumerate().skip(first + 1) {
                        let gap = (0..3)
                            .map(|row| {
                                reference.approximate(&largest_magnitude(&difference(
                                    &matrix[row],
                                    &other[row],
                                )))
                            })
                            .fold(0.0, f64::max);
                        assert!(
                            gap > STABILIZER_DISTINCT,
                            "{name}: words {first} and {second}"
                        );
                    }
                }
                let mut images: Vec<DVec3> = Vec::new();
                for matrix in &matrices {
                    let image = approximate(&mut reference, &apply(matrix, &exact.generator));
                    if images
                        .iter()
                        .all(|seen| (*seen - image).abs().max_element() > STABILIZER_MARGIN)
                    {
                        images.push(image);
                    }
                }
                assert_eq!(
                    images.len(),
                    usize::try_from(rule.sides).unwrap_or(0),
                    "{name}: images of the generator point"
                );
                let centre = approximate(&mut reference, corner);
                let first = images[0];
                images.sort_by(|left, right| {
                    chart_angle(geometry, centre, first, *left)
                        .total_cmp(&chart_angle(geometry, centre, first, *right))
                });
                let orientation = least_side(&images, centre, 1.0).signum();
                assert!(
                    least_side(&images, centre, orientation) > 0.0,
                    "{name}: the corner lies outside"
                );
                let region = region_of(&exact, rule);
                let samples: Vec<Vector> = REGION_WEIGHTS
                    .iter()
                    .map(|weights| {
                        surface_point(measure, &domain_centre, &region, &weights[..region.len()])
                    })
                    .collect();
                let regions: Vec<Vec<DVec3>> = matrices
                    .iter()
                    .map(|matrix| {
                        region
                            .iter()
                            .map(|point| approximate(&mut reference, &apply(matrix, point)))
                            .collect()
                    })
                    .collect();
                for (matrix, image) in matrices.iter().zip(&regions) {
                    for sample in &samples {
                        let point = approximate(&mut reference, &apply(matrix, sample));
                        assert!(
                            least_side(&images, point, orientation) > -STABILIZER_MARGIN,
                            "{name}: a sample of an image of the region lies outside the face"
                        );
                        inside += 1;
                    }
                    assert_eq!(image.len(), region.len());
                }
                let region_orientation =
                    least_side(&regions[0], approximate(&mut reference, &samples[0]), 1.0).signum();
                let exact_images: Vec<Vector> = matrices
                    .iter()
                    .map(|matrix| apply(matrix, &exact.generator))
                    .collect();
                for pair in 0..exact_images.len() {
                    let [start, end] = [pair, (pair + 1) % exact_images.len()]
                        .map(|index| exact_images[index].clone());
                    for weights in FACE_WEIGHTS {
                        let point = surface_point(
                            measure,
                            &domain_centre,
                            &[corner.clone(), start.clone(), end.clone()],
                            &weights,
                        );
                        let point = approximate(&mut reference, &point);
                        if least_side(&images, point, orientation) <= STABILIZER_MARGIN {
                            continue;
                        }
                        let sides: Vec<f64> = regions
                            .iter()
                            .map(|image| {
                                let turn = if matrix_reverses(image, &regions[0]) {
                                    -1.0
                                } else {
                                    1.0
                                };
                                least_side(image, point, region_orientation * turn)
                            })
                            .collect();
                        if sides.iter().any(|side| side.abs() <= STABILIZER_MARGIN) {
                            continue;
                        }
                        let holding = sides.iter().filter(|&&side| side > 0.0).count();
                        assert_eq!(
                            holding, 1,
                            "{name}: a point of the face lies in {holding} images of the region"
                        );
                        covered += 1;
                    }
                }
                let ends = [
                    exact.generator.clone(),
                    apply(&walls[rule.centre].pairing, &exact.generator),
                ];
                let middle = surface_point(measure, &domain_centre, &ends, &[1, 1]);
                let foot = exact.feet[rule.centre]
                    .clone()
                    .unwrap_or_else(|| panic!("{name}: no foot"));
                let off = reference.approximate(&largest_magnitude(&difference(&middle, &foot)));
                assert!(
                    off <= STABILIZER_MARGIN,
                    "{name}: the foot is {off:e} from the midpoint of edge 0"
                );
                let flat = &face.kinds[kind].matrices;
                for (first, matrix) in flat.iter().enumerate() {
                    for other in &flat[first + 1..] {
                        assert!(
                            (*matrix - *other)
                                .abs()
                                .to_cols_array()
                                .iter()
                                .copied()
                                .fold(0.0, f64::max)
                                > STABILIZER_DISTINCT,
                            "{name}"
                        );
                    }
                }
                types += 1;
            }
        }
        println!(
            "{types} face types, {inside} samples of the images of the regions, {covered} points of the faces"
        );
        assert_eq!((types, inside, covered), STABILIZED);
    }

    const STABILIZED: (usize, usize, usize) = (42, 1728, 481);

    fn matrix_reverses(image: &[DVec3], home: &[DVec3]) -> bool {
        let turn = |polygon: &[DVec3]| polygon[0].dot(polygon[1].cross(polygon[2]));
        turn(image) * turn(home) < 0.0
    }

    const MEETING_TOLERANCE: f64 = 1e-9;

    fn edge_midpoint(
        exact_type: &ExactType,
        walls: &[crate::reference::Wall],
        exact: &ExactWythoff,
        edge: usize,
    ) -> Vector {
        let (word, side) = exact_type.edge_wall(edge);
        let foot = exact.feet[side]
            .clone()
            .unwrap_or_else(|| panic!("side {side} has no foot"));
        apply(&word_matrix(walls, &word), &foot)
    }

    fn reversed(word: &Word) -> Word {
        word.letters().iter().rev().copied().collect()
    }

    fn joined(parts: &[&Word]) -> Word {
        parts
            .iter()
            .flat_map(|part| part.letters().iter().copied())
            .collect()
    }

    fn determinant(reference: &mut Reference, matrix: &Matrix) -> f64 {
        let column = |index: usize| [0, 1, 2].map(|row| matrix[row][index].clone());
        let value =
            escher_reference::dot(&column(0), &escher_reference::cross(&column(1), &column(2)));
        reference.approximate(&value)
    }

    #[test]
    #[expect(
        clippy::too_many_lines,
        reason = "the test reads each meeting from the table and checks its element, midpoint, side, and determinant in one pass"
    )]
    fn each_meeting_of_several_face_types_carries_the_neighbour_onto_the_face_across_its_edge() {
        let mut reference = Reference::new();
        let mut kinds_seen = [0; 4];
        let (mut meetings, mut mirrors, mut arrangements) = (0, 0, 0);
        for (text, marks, chosen) in several_picture_set() {
            let (domain, face) = several_face(text, marks);
            let walls = reference_walls(&domain);
            let exact = exact_wythoff(&domain, marks);
            let rules = type_rules(signature_orders(text), marks);
            let types: Vec<ExactType> = rules
                .iter()
                .map(|&rule| ExactType::new(&mut reference, &domain, &exact, rule))
                .collect();
            for arrangement in &chosen {
                let name = format!("{text} {} {}", marks_text(marks), arrangement.id());
                let table = arrangement.table();
                let reading = read_types(&rules, table);
                let edges = face
                    .edges(arrangement)
                    .unwrap_or_else(|error| panic!("{name}: {error}"));
                let firsts: Vec<usize> = reading
                    .kinds
                    .iter()
                    .scan(0, |first, &kind| {
                        let start = *first;
                        *first += usize::try_from(rules[kind].sides).unwrap_or(0);
                        Some(start)
                    })
                    .collect();
                for (picture, &kind) in reading.kinds.iter().enumerate() {
                    let base = &reading.bases[picture];
                    let base_coset = trace_from(table, 0, base);
                    let carrying = word_matrix(&walls, base);
                    for edge in 0..types[kind].starts.len() {
                        let label = format!("{name}: edge {edge} of picture {picture}");
                        let meeting = edges[firsts[picture] + edge];
                        let (word, side) = types[kind].edge_wall(edge);
                        let coset = trace_from(table, base_coset, &word);
                        let across = [(side + 2) % 3, side]
                            .into_iter()
                            .find(|&corner| corner != rules[kind].corner)
                            .unwrap_or(rules[kind].corner);
                        let (other, element, beyond) = if let Some(other) =
                            rules.iter().position(|rule| rule.corner == across)
                        {
                            (other, reading.elements[other][coset], None)
                        } else {
                            let mirror = if side == across {
                                (across + 1) % 3
                            } else {
                                across
                            };
                            let mirror_word =
                                Word::from_iter([crate::golden_images::letter(mirror)]);
                            let beyond = trace_from(table, coset, &mirror_word);
                            (kind, reading.elements[kind][beyond], Some(mirror_word))
                        };
                        let (neighbour, neighbour_word) = element;
                        assert_eq!(
                            usize::try_from(meeting.picture()).unwrap_or(usize::MAX),
                            neighbour,
                            "{label}"
                        );
                        let partner = usize::try_from(meeting.partner()).unwrap_or(usize::MAX);
                        let empty = Word::new();
                        let element_word = joined(&[
                            base,
                            &word,
                            beyond.as_ref().unwrap_or(&empty),
                            &reversed(&types[other].words[neighbour_word]),
                            &reversed(&reading.bases[neighbour]),
                        ]);
                        assert_eq!(trace_from(table, 0, &element_word), 0, "{label}");
                        let element_matrix = word_matrix(&walls, &element_word);
                        let neighbour_carrying = word_matrix(&walls, &reading.bases[neighbour]);
                        let there = apply(
                            &neighbour_carrying,
                            &edge_midpoint(&types[other], &walls, &exact, partner),
                        );
                        let here = apply(
                            &carrying,
                            &edge_midpoint(&types[kind], &walls, &exact, edge),
                        );
                        let moved = apply(&element_matrix, &there);
                        let off = reference
                            .approximate(&largest_magnitude(&difference(&moved, &here)))
                            / reference.approximate(&largest_magnitude(&here)).max(1.0);
                        assert!(
                            off <= MEETING_TOLERANCE,
                            "{label}: the partner {partner} lands {off:e} away"
                        );
                        let wall = exact.perpendiculars[side]
                            .clone()
                            .unwrap_or_else(|| panic!("{label}: side {side} has no perpendicular"));
                        let back = word_matrix(&walls, &reversed(&joined(&[base, &word])));
                        let mut value = |point: &Vector| {
                            let value = escher_reference::dot(&wall, &apply(&back, point));
                            reference.approximate(&value)
                        };
                        let home = apply(&carrying, &exact.vertices[rules[kind].corner]);
                        let neighbour_centre = apply(
                            &element_matrix,
                            &apply(&neighbour_carrying, &exact.vertices[rules[other].corner]),
                        );
                        assert!(
                            value(&home) * value(&neighbour_centre) < 0.0,
                            "{label}: the neighbour lies on the same side of the edge"
                        );
                        let sign = determinant(&mut reference, &element_matrix);
                        assert_eq!(sign < 0.0, meeting.mirrored(), "{label}");
                        let between = other != kind;
                        kinds_seen[usize::from(between) * 2 + usize::from(meeting.mirrored())] += 1;
                        mirrors += usize::from(beyond.is_some());
                        meetings += 1;
                    }
                }
                arrangements += 1;
            }
        }
        println!(
            "{arrangements} arrangements, {meetings} meetings, {mirrors} across a mirror (turned and mirrored within a type, turned and mirrored between types): {kinds_seen:?}"
        );
        assert_eq!(
            (arrangements, meetings, mirrors, kinds_seen),
            MEETING_GEOMETRY
        );
    }

