    fn in_flat_polygon(reference: &mut Reference, polygon: &[Flat], point: &Flat) -> bool {
        let count = polygon.len();
        (0..count).all(|side| {
            let start = &polygon[(side + count - 1) % count];
            let end = &polygon[side];
            let turn = escher_reference::sub(
                &escher_reference::mul(
                    &escher_reference::sub(&end[0], &start[0]),
                    &escher_reference::sub(&point[1], &start[1]),
                ),
                &escher_reference::mul(
                    &escher_reference::sub(&end[1], &start[1]),
                    &escher_reference::sub(&point[0], &start[0]),
                ),
            );
            reference.approximate(&turn) >= -IN_REGION
        })
    }

    struct SeveralSeamType {
        exact: ExactType,
        flat_region: Vec<Flat>,
        mask: ExactMask,
    }

    impl SeveralSeamType {
        fn new(
            reference: &mut Reference,
            domain: &FundamentalDomain,
            exact: &ExactWythoff,
            rule: TypeRule,
        ) -> Self {
            let measure = Measure::of(domain.geometry());
            let exact_type = ExactType::new(reference, domain, exact, rule);
            let after = (rule.corner + 1) % 3;
            let shape = if rule.both() {
                RegionShape::BothOn
            } else if rule.centre == after {
                RegionShape::CentreAfter
            } else {
                RegionShape::CentreBefore
            };
            let foot = exact.feet[rule.centre]
                .clone()
                .unwrap_or_else(|| panic!("side {} has no foot", rule.centre));
            let direction = direction_toward(measure, &exact_type.region[0], &foot);
            let flat_region = face_region(reference, rule.sides, shape, &direction);
            let vertices: Vec<[f64; 3]> = exact_type
                .region
                .iter()
                .map(|point| approximate(reference, point).to_array())
                .collect();
            let sides = domain.sides();
            let oriented_wall = |reference: &mut Reference, side: usize| {
                let wall = exact.perpendiculars[side]
                    .clone()
                    .unwrap_or_else(|| panic!("side {side} has no perpendicular"));
                let sign = reference
                    .approximate(&escher_reference::dot(&wall, &exact.vertices[rule.corner]));
                approximate(reference, &wall)
                    .to_array()
                    .map(|value| -sign.signum() * value)
            };
            let mut covectors = vec![
                sides[rule.corner].covector().to_array(),
                sides[after].covector().to_array(),
            ];
            if rule.both() {
                covectors.push(oriented_wall(reference, after));
                covectors.push(oriented_wall(reference, rule.corner));
            } else {
                covectors.push(oriented_wall(reference, rule.centre));
            }
            let mask = ExactMask::new(
                reference,
                measure,
                &vertices,
                &covectors,
                MaskRule::FaceRegion {
                    sides: rule.sides,
                    shape,
                },
            );
            Self {
                exact: exact_type,
                flat_region,
                mask,
            }
        }

        fn face_point(
            &self,
            reference: &mut Reference,
            walls: &[crate::reference::Wall],
            flat: &Flat,
        ) -> Option<Vector> {
            let (word, flat_matrix) =
                self.exact
                    .words
                    .iter()
                    .zip(&self.exact.flats)
                    .find(|(_, flat_matrix)| {
                        in_flat_polygon(
                            reference,
                            &self.flat_region,
                            &flat_inverse_apply(flat_matrix, flat),
                        )
                    })?;
            let in_region = self
                .mask
                .inverse(reference, &flat_inverse_apply(flat_matrix, flat));
            Some(apply(&word_matrix(walls, word), &in_region))
        }
    }

